const manifest = await readJson(manifestPath, "deployment manifest");
assertManifest(manifest);

const artifacts = {};
for (const [name, path] of Object.entries(artifactPaths)) {
  const artifact = await readJson(path, `${name} artifact`);
  if (!Array.isArray(artifact.abi)) {
    throw new Error(`${name} artifact is missing an ABI array.`);
  }
  artifacts[name] = artifact;
}

const contracts = {};
for (const name of Object.keys(artifactPaths)) {
  const manifestContract = manifest.contracts[name];
  contracts[name] = {
    address: manifestContract.address,
    blockNumber: manifestContract.blockNumber,
    transactionHash: manifestContract.transactionHash,
    runtimeBytecodeHash: manifestContract.runtimeBytecodeHash,
    abi: minimalAbi(artifacts[name].abi, name),
  };
}

